import { SUPPORTED_TOOLS, MAX_FILE_SIZE_MB } from './tools.js';

// Вопросы с цифрами внутри: лимиты берутся из того же SUPPORTED_TOOLS, что и
// форма, иначе JSON-LD начнёт утверждать про 20 файлов, когда инструмент
// принимает 10, и поисковик получит разметку, не совпадающую с текстом страницы.
const perToolLimits = Object.values(SUPPORTED_TOOLS).map((tool) => tool.maxFiles);
const MIN_FILES_LIMIT = Math.min(...perToolLimits);
const MAX_FILES_LIMIT = Math.max(...perToolLimits);
const IMAGES_TO_PDF_LIMIT = SUPPORTED_TOOLS['jpg-to-pdf'].maxFiles;

